function step(title, explanation, key, action, mode, text, extra = {}) {
  return {
    title,
    explanation,
    key,
    action,
    mode,
    text,
    expected:
      mode === 'c'
        ? '명령줄에 입력 중 · 아직 실행 전'
        : mode === 'r?'
          ? '치환 확인 중 · 현재 강조된 항목을 확인하세요'
          : '일반 모드 · 변경된 줄을 비교하세요',
    recovery:
      '입력 중인 명령줄은 Esc로 취소할 수 있습니다. 이미 실행했다면 일반 모드에서 u로 되돌릴 수 있습니다. 치환 확인 중에는 q로 남은 치환을 중단하세요. q는 이미 바꾼 내용을 되돌리지는 않습니다.',
    ...extra,
  };
}
function command(title, explanation, key, before, text, after) {
  return step(
    title,
    explanation,
    key,
    `${key}를 입력하세요. 아직 Enter는 누르지 마세요.`,
    'c',
    text,
    { commandType: ':', command: before + key, ...after },
  );
}
function colon(text) {
  return command(
    '명령줄을 엽니다',
    '콜론으로 명령줄에 들어갑니다. 저장 때 사용했던 것과 같은 명령줄입니다.',
    ':',
    '',
    text,
    { command: '' },
  );
}
