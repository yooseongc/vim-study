function step(title, explanation, key, action, mode, text, extra = {}) {
  return {
    title,
    explanation,
    key,
    action,
    mode,
    text,
    expected:
      mode === 'c'
        ? '명령줄에 입력 중 · 아직 실행 전'
        : mode === 'no'
          ? '편집 범위 대기 · 내용은 그대로'
          : mode === 'i'
            ? '입력 모드 · 이번 단계의 내용을 확인하세요'
            : '일반 모드 · 바뀐 줄과 커서 위치를 확인하세요',
    recovery:
      '아직 명령을 완성하지 않았다면 Esc로 취소할 수 있습니다. 파일이 예상과 다르면 현재 상태 점검으로 비교하세요. 반복할 변경이 헷갈리면 처음부터 다시 연습해도 됩니다.',
    ...extra,
  };
}
